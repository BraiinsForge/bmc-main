import { readdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const GENERATED_ROOT = fileURLToPath(new URL('../src/proto/gen/web/', import.meta.url));
const GENERATED_MARKER = '// @generated by protoc-gen-es';

async function findGeneratedBindings(directory: string): Promise<string[]> {
    const files: string[] = [];

    for (const entry of await readdir(directory, { withFileTypes: true })) {
        const path = `${directory}/${entry.name}`;

        if (entry.isDirectory()) {
            files.push(...(await findGeneratedBindings(path)));
        } else if (entry.name.endsWith('_pb.ts')) {
            files.push(path);
        }
    }

    return files;
}

for (const file of await findGeneratedBindings(GENERATED_ROOT)) {
    const source = await readFile(file, 'utf8');
    const markerIndex = source.indexOf(GENERATED_MARKER);

    if (markerIndex === -1) {
        throw new Error(`generated marker missing from ${file}`);
    }

    const prefix = source.slice(0, markerIndex);
    const unexpectedLine = prefix.split('\n').find(line => line !== '' && !line.startsWith('//'));

    if (unexpectedLine !== undefined) {
        throw new Error(`unexpected content before generated marker in ${file}: ${unexpectedLine}`);
    }

    if (prefix !== '') {
        await writeFile(file, source.slice(markerIndex));
    }
}
